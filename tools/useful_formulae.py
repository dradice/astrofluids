#!/usr/bin/env python3
"""Build a compact, two-column printable PDF of the useful formulae (Appendix B).

The formulae live only in appendices/equation-sheet.qmd. This script copies
it into a standalone Quarto document under _worksheets/build/, replaces references
to chapters and appendices with plain text ("Chapter 18"), and renders it to
_worksheets/useful-formulae.pdf with Typst, using the same math macros as the book.
Equations keep the numbers they have in the book, so "Eq. (B.12)" means the same
thing on paper and on the website.

Usage:
  python3 tools/useful_formulae.py
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from chapters import APPENDICES, PARTS, ROOT  # noqa: E402

SLUG = "equation-sheet"  # source file; never renamed
HANDOUT = "useful-formulae"
OUT = ROOT / "_worksheets"
BUILD = OUT / "build"

PROJECT = """\
# Generated by tools/useful_formulae.py; do not edit.
project:
  type: default
  output-dir: ..
"""


def section_names():
    """Map sec-<key> to "Chapter N" or "Appendix X"."""
    names = {}
    chapters = [key for _, cs in PARTS for _, key, *_ in cs]
    for n, key in enumerate(chapters, start=1):
        names[f"sec-{key}"] = f"Chapter {n}"
    for n, (_, key, *_) in enumerate(APPENDICES):
        names[f"sec-{key}"] = f"Appendix {chr(ord('A') + n)}"
    return names


def main():
    letter = next(chr(ord("A") + n) for n, (slug, *_) in enumerate(APPENDICES) if slug == SLUG)
    lines = (ROOT / "appendices" / f"{SLUG}.qmd").read_text().splitlines()
    title = re.sub(r"\s*\{#.*\}\s*$", "", lines[0]).lstrip("# ").strip()
    text = "\n".join(lines[1:])

    names = section_names()

    def replace(m):
        if m.group(1) not in names:
            sys.exit(f"{SLUG}: cannot print a reference to {m.group(1)}")
        return names[m.group(1)]

    text = re.sub(r"@(sec-[\w-]+)", replace, text)
    text = text.replace("This appendix collects", "This sheet collects", 1)
    if re.search(r"@(?:eq|fig|exr|cnj)-", text):
        sys.exit(f"{SLUG}: only references to chapters and appendices can be printed")

    front = f"""\
---
title: "{title}"
subtitle: "ASTRO 442 · Astrophysical Fluid Dynamics · Appendix {letter}"
format:
  typst:
    papersize: us-letter
    margin:
      x: 1.4cm
      y: 1.6cm
    columns: 2
    fontsize: 8.5pt
    section-numbering: "{letter}.1.1"
filters:
  - ../../filters/macros.lua
---

```{{=typst}}
#let equation-numbering = n => "({letter}." + str(n) + ")"
#show figure.where(kind: "quarto-float-tbl"): set figure(numbering: n => "{letter}." + str(n))
#set par(justify: false)
#show math.equation.where(block: true): set block(spacing: 0.7em)
#show heading: set block(above: 1.1em, below: 0.6em)
```

"""
    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / "_quarto.yml").write_text(PROJECT)
    src = BUILD / f"{HANDOUT}.qmd"
    src.write_text(front + text.strip() + "\n")
    subprocess.run(["quarto", "render", src.name, "--to", "typst"], cwd=BUILD, check=True)
    print(f"-> {(OUT / src.with_suffix('.pdf').name).relative_to(ROOT)}")


if __name__ == "__main__":
    main()
