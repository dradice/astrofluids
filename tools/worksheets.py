#!/usr/bin/env python3
"""Build printable PDF handouts of the in-class worksheets.

The worksheets live only in the chapters (section `## In-class worksheet`). This
script copies each one into a standalone Quarto document under _worksheets/build/,
drops the instructor-only blocks (`when-profile="solutions"`), and renders it to
_worksheets/<NN>-<slug>.pdf with Typst, using the same math macros and PDF styles
as the book. Equations and figures keep the numbers they have in the book, so
"Eq. (9.14)" means the same thing on paper and on the website.

A worksheet must not refer to equations, figures or sections outside itself.

Usage:
  python3 tools/worksheets.py              all chapters
  python3 tools/worksheets.py sound-waves  one or more chapters, by slug or path
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from chapters import PARTS, ROOT  # noqa: E402

OUT = ROOT / "_worksheets"
BUILD = OUT / "build"

WORKSHEET = re.compile(r"^## In-class worksheets?\b")
FENCE = re.compile(r"^(:{3,})\s*(.*)$")
LABEL = re.compile(r"\{#(eq|fig)-[\w-]+")
REF = re.compile(r"@((?:eq|fig|sec|exr|tbl|cnj)-[\w-]+)")
IMAGE = re.compile(r"\]\(\.\./(figures/[^)\s]+)\)")

PROJECT = """\
# Generated by tools/worksheets.py; do not edit.
project:
  type: default
  output-dir: ..
"""


def strip_solutions(lines):
    """Remove fenced divs marked when-profile="solutions" (and everything nested in them)."""
    out, stack = [], []  # stack of (fence length, is solutions block)
    for line in lines:
        m = FENCE.match(line)
        hidden = any(s for _, s in stack)
        if m and m.group(2):  # opening fence
            stack.append((len(m.group(1)), 'when-profile="solutions"' in m.group(2)))
            if not hidden and not stack[-1][1]:
                out.append(line)
            continue
        if m and not m.group(2) and stack:  # closing fence
            _, sol = stack.pop()
            if not hidden and not sol:
                out.append(line)
            continue
        if not hidden:
            out.append(line)
    return out


def split_chapter(path):
    """Return (title, lines before the worksheet, worksheet body) of a chapter."""
    # HTML comments hold dropped text, whose labels Quarto does not number.
    lines = re.sub(r"<!--.*?-->", "", path.read_text(), flags=re.S).splitlines()
    title = re.sub(r"\s*\{#.*\}\s*$", "", lines[0]).lstrip("# ").strip()
    start = next((i for i, l in enumerate(lines) if WORKSHEET.match(l)), None)
    if start is None:
        return title, None, None
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return title, lines[:start], lines[start + 1:end]


def count_labels(lines):
    """Number of numbered equations and figures, as Quarto counts them."""
    counts = {"eq": 0, "fig": 0}
    for line in strip_solutions(lines):
        for kind in LABEL.findall(line):
            counts[kind] += 1
    return counts


def handout(number, slug, title, before, body):
    counts = count_labels(before)
    body = strip_solutions(body)
    text = "\n".join(body)

    # References must stay inside the worksheet.
    defined = set(re.findall(r"\{#((?:eq|fig|sec|exr|tbl|cnj)-[\w-]+)", text))
    missing = sorted(set(REF.findall(text)) - defined)
    if missing:
        sys.exit(f"{slug}: the worksheet refers to {', '.join(missing)}, outside the worksheet")

    # Figures: copy them next to the document (Typst cannot read outside the project).
    for fig in IMAGE.findall(text):
        dest = BUILD / fig
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / fig, dest)
    text = IMAGE.sub(r"](\1)", text)

    # Subsections become top-level headings of the handout.
    text = re.sub(r"^###", "##", text, flags=re.M)

    numbering = f"""\
```{{=typst}}
#let equation-numbering = n => "({number}." + str(n) + ")"
#counter(math.equation).update({counts["eq"]})
#show figure.where(kind: "quarto-float-fig"): set figure(numbering: n => "{number}." + str(n))
#counter(figure.where(kind: "quarto-float-fig")).update({counts["fig"]})
```
"""
    # Citations (e.g. figure credits): copy the bibliography only when needed, since
    # Typst prints a reference list whenever there is one.
    bib = ""
    if re.search(r"(?<![\w.])@(?!(?:eq|fig|sec|exr|tbl|cnj)-)[A-Za-z]", text):
        shutil.copy2(ROOT / "references.bib", BUILD / "references.bib")
        bib = "bibliography: references.bib\n"

    front = f"""\
---
title: "{title}"
subtitle: "ASTRO 442 · In-class worksheet · Chapter {number}"
format:
  typst:
    papersize: us-letter
    margin:
      x: 2cm
      y: 2cm
    include-before-body: ../../styles/pdf.typ
{bib}filters:
  - ../../filters/macros.lua
---

"""
    src = BUILD / f"{number:02d}-{slug}.qmd"
    src.write_text(front + numbering + "\n" + text.strip() + "\n")
    return src


def main(args):
    chapters = [(s, t) for _, chs in PARTS for s, _, t, _ in chs]
    wanted = {Path(a).stem for a in args}
    unknown = wanted - {s for s, _ in chapters}
    if unknown:
        sys.exit(f"unknown chapter(s): {', '.join(sorted(unknown))}")

    BUILD.mkdir(parents=True, exist_ok=True)
    (BUILD / "_quarto.yml").write_text(PROJECT)
    sources = []
    for number, (slug, _) in enumerate(chapters, start=1):
        if wanted and slug not in wanted:
            continue
        path = ROOT / "chapters" / f"{slug}.qmd"
        title, before, body = split_chapter(path)
        if body is None:
            print(f"{slug}: no worksheet, skipped")
            continue
        sources.append(handout(number, slug, title, before, body))

    for src in sources:
        subprocess.run(["quarto", "render", src.name, "--to", "typst"], cwd=BUILD, check=True)
        print(f"-> {(OUT / src.with_suffix('.pdf').name).relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1:])
